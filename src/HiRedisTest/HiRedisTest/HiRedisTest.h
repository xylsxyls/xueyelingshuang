/** 现行接口与功能判定
单连接默认 127.0.0.1:6379，密码为空，数据库 0（负值跳过 SELECT）；连接和命令超时默认 3000 毫秒，非正值回退到 3000。TCP 端口允许 1～65535，KeepAlive 默认打开。每个池连接占一个服务端会话及一个套接字。
池的 init(config) 默认预建 1 个、最多 1 个。创建前修改 m_poolMinConnections 为非负数（含 0），m_poolMaxConnections 设为不小于下限的正整数或 -1（总数不设人为上限）。固定大小 init(config,count) 接受正数并覆盖两项弹性配置。耗尽时可建连的名额包含正在建连数；达到上限后 acquire(0) 不等待、正数等待指定毫秒、负数一直等待，默认 3000 毫秒。该期限用于等名额，实际联网另按连接/读写超时。归还后最多保留配置的空闲数；关闭会唤醒等待者并使旧代次的借用失败，即使随后立刻重新初始化。关闭立即释放空闲连接，外借对象在归还时释放。池析构可以与已经借出的连接归还并行，调用方须保证池上的其他成员调用在析构前已经结束。
无参数执行功能，未知参数返回 2。setTable 按列位置保留首尾及连续空字段，多字符分隔符同样生效。字段中含有分隔符时不会转义；需要区分该情况时选择不出现在数据中的分隔符。
*/

