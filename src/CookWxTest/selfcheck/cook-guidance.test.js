test('未开始或关闭同步不排队；已开始卸载只保存一次且不弹框', () => {
  for (const optedIn of [false, true]) {
    const { page, app, calls } = fixture('cook', { plan: plan([task('front', 0, 30)], optedIn) })
    if (!optedIn) page.toggleRunning()
    page.onUnload()
    assert.equal(app.globalData.pendingCookSyncReports.length, 0)
    assert.equal(calls.modals.length, 0)
  }
  const { page, app, calls } = fixture('cook', { plan: plan([task('front', 0, 3), task('next', 3, 30)], true) })
  page.toggleRunning()
  runtime.tick(page.runtime, 3)
  page.onUnload()
  page.onUnload()
  assert.equal(app.globalData.pendingCookSyncReports.length, 1)
  assert.equal(app.globalData.pendingCookSyncReports[0].items[0].durationOverrides[0].durationSeconds, 3)
  assert.equal(calls.modals.length, 0)
})

test('全部完成同步确认后才提示成果；取消不写入且只询问一次', async () => {
  for (const confirm of [false, true]) {
    const { page, calls, app } = fixture('cook', { plan: plan([task('front', 0, 3)], true) })
    page.toggleRunning()
    runtime.tick(page.runtime, 3)
    page.refreshView()
    assert.equal(page.data.finishing, true)
    assert.equal(calls.modals.length, 0, '原生退出提醒关闭前不得再弹模态框')
    calls.enable[0].success({})
    await flush()
    calls.disable[0].success({})
    await flush()
    assert.equal(calls.modals.length, 1)
    calls.modals[0].success({ confirm })
    await flush()
    assert.equal(calls.sync.length, confirm ? 1 : 0)
    assert.equal(page.data.finishing, false)
    assert.equal(calls.modals[1].title, '流程完成')
    assert.equal(app.globalData.pendingCookSyncReports.length, 0)
    page.markRuntimeComplete()
    assert.equal(calls.modals.length, 2)
    page.onUnload()
  }
})

test('完成后提醒关闭晚到且页面已隐藏，恢复可见后才询问同步', async () => {
  const { page, calls } = fixture('cook', { plan: plan([task('front', 0, 3)], true) })
  page.toggleRunning()
  runtime.tick(page.runtime, 3)
  page.refreshView()
  calls.enable[0].success({})
  await flush()
  page.onHide()
  calls.disable[0].success({})
  await flush()
  assert.equal(calls.modals.length, 0)
  page.onShow()
  await flush()
  assert.equal(calls.modals[0].title, '同步到个性化？')
  calls.modals[0].success({ confirm: false })
  assert.equal(calls.modals[1].title, '流程完成')
  page.onUnload()
})