    await sim.data(mine, data => !data.loading && data.account.userId === user.account.userId, '本人资料加载')
    const ownLayout = await layout(mine)
    publicLayout.forEach((position, index) => { assert.ok(Math.abs(position.left - ownLayout[index].left) <= 2); assert.ok(Math.abs(position.top - ownLayout[index].top) <= 2) })
    return { authorId: authorData.profile.userId, sameAvatarSourceAndInitial: true, sameAvatarStyles: true, sameProfileGeometry: true, onlyTwoPublicTabs: true }
